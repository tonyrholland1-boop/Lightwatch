export function SuccessDialog({ open, onClose, report, areaName }) {
  if (!open) return null;
  return (
    <div
      className="dialog-backdrop"
      role="presentation"
      onMouseDown={(event) => {
        if (event.target === event.currentTarget) onClose();
      }}
    >
      <div
        className="dialog"
        role="dialog"
        aria-modal="true"
        aria-labelledby="report-dialog-title"
        onKeyDown={(event) => {
          if (event.key === 'Escape') onClose();
        }}
      >
        <span className="dialog__icon" aria-hidden="true">
          <Icon name="check" size={18} />
        </span>
        <h2 id="report-dialog-title">Report received</h2>
        <p>
          Thanks for sharing an update{areaName ? ` for ${areaName}` : ''}. Your
          {report ? ` ${report.status} ` : ' '}report is now part of the community feed and
          has been counted toward the area status.
        </p>
        <p style={{ marginTop: 10, color: 'var(--subtle)', fontSize: 12 }}>
          Community reports are unverified. Other visitors will see it labelled with its
          timestamp and source.
        </p>
        <div className="dialog__actions">
          <button type="button" className="btn btn--light" onClick={onClose}>
            Continue
          </button>
        </div>
      </div>
    </div>
  );
}
